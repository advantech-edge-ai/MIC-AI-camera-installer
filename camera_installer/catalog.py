"""Driver catalog: fetch and parse internet_list.sh from the GitHub repo.

The list is a bash file generated by gen_driver_lists.py. It is parsed with
regexes only -- never sourced or executed.
"""
from __future__ import annotations

import re
import urllib.error
import urllib.request
from typing import Dict, List, NamedTuple, Optional

# Fetched straight from raw.githubusercontent.com: the github.com/.../raw/...
# URL Chris's script uses is only a redirect to it and sometimes stalls.
LIST_URL = ("https://raw.githubusercontent.com/advantech-edge-ai/MIC-AI-camera-driver"
            "/main/internet_list.sh")
# Not the repo page: GitHub answers HEAD on repo pages with 504 or no reply at
# all, intermittently. The front page answers HEAD reliably.
DEFAULT_PROBE = "https://github.com/"
USER_AGENT = "advantech-camera-installer"


class Package(NamedTuple):
    vendor: str
    sensor: str
    platform: str   # orin_nx_orin_nano | agx_orin | thor
    board: str      # mic_742, mic_733ao, ...
    jetpack: str    # jp6.2, igx2.0, ...
    url: str

    @property
    def key(self) -> str:
        return "/".join((self.vendor, self.sensor, self.platform, self.board, self.jetpack))

    @property
    def camera(self):
        return (self.vendor, self.sensor)

    @property
    def family(self) -> str:
        return "thor" if self.platform == "thor" else "orin"

    @property
    def asset_name(self) -> str:
        return self.url.rsplit("/", 1)[-1]


class Catalog(NamedTuple):
    probe: str
    packages: List[Package]
    board_labels: Dict[str, str]
    platform_labels: Dict[str, str]

    def board_label(self, board: Optional[str]) -> str:
        if not board:
            return "Unknown"
        return self.board_labels.get(board) or board.upper().replace("_", "-")

    def platform_label(self, platform: Optional[str]) -> str:
        if not platform:
            return "Unknown"
        return self.platform_labels.get(platform, platform)

    def platform_of_board(self, board: Optional[str]) -> Optional[str]:
        for p in self.packages:
            if p.board == board:
                return p.platform
        return None


class CatalogError(Exception):
    pass


_SCALAR = r'^\s*{name}="([^"]*)"'
_ARRAY = r"declare\s+-gA\s+{name}=\((.*?)^\)"
_ENTRY = re.compile(r'\[\s*"([^"]+)"\s*\]\s*=\s*"([^"]*)"')


def _scalar(text: str, name: str) -> Optional[str]:
    m = re.search(_SCALAR.format(name=name), text, re.M)
    return m.group(1) if m else None


def _array(text: str, name: str) -> Dict[str, str]:
    m = re.search(_ARRAY.format(name=name), text, re.M | re.S)
    if not m:
        return {}
    out = {}
    for line in m.group(1).splitlines():
        if line.lstrip().startswith("#"):
            continue
        em = _ENTRY.search(line)
        if em:
            out[em.group(1)] = em.group(2)
    return out


def parse(text: str) -> Catalog:
    if "INTERNET_LIST" not in text:
        raise CatalogError("Driver list has unexpected format (no INTERNET_LIST).")
    gh_release = _scalar(text, "GH_RELEASE") or ""
    packages = []
    for key, val in _array(text, "INTERNET_LIST").items():
        parts = key.split("/")
        if len(parts) != 5:
            continue
        url = val.replace("${GH_RELEASE}", gh_release).replace("$GH_RELEASE", gh_release)
        if not url.startswith("https://"):
            continue
        packages.append(Package(*parts, url=url))
    if not packages:
        raise CatalogError("Driver list is empty.")
    packages.sort(key=lambda p: p.key)
    return Catalog(
        probe=_scalar(text, "INTERNET_PROBE") or DEFAULT_PROBE,
        packages=packages,
        board_labels=_array(text, "BOARD_LABEL"),
        platform_labels=_array(text, "PLATFORM_LABEL"),
    )


def open_url(url: str, timeout: float = 15, method: str = "GET"):
    req = urllib.request.Request(url, method=method, headers={"User-Agent": USER_AGENT})
    return urllib.request.urlopen(req, timeout=timeout)


def check_network(url: str = DEFAULT_PROBE, timeout: float = 8) -> None:
    """Raise OSError if *url* cannot be reached. Any HTTP status counts as
    reachable -- the request got through, which is all this checks."""
    try:
        with open_url(url, timeout=timeout, method="HEAD"):
            pass
    except urllib.error.HTTPError:
        pass


def fetch(url: str = LIST_URL, timeout: float = 15) -> Catalog:
    if url.startswith("file://") or "://" not in url:
        path = url[len("file://"):] if url.startswith("file://") else url
        with open(path, encoding="utf-8") as f:
            return parse(f.read())
    with open_url(url, timeout=timeout) as resp:
        return parse(resp.read().decode("utf-8", "replace"))


def remote_size(url: str, timeout: float = 10) -> Optional[int]:
    try:
        with open_url(url, timeout=timeout, method="HEAD") as resp:
            n = resp.headers.get("Content-Length")
            return int(n) if n else None
    except (OSError, ValueError):
        return None


def human_size(n: Optional[int]) -> str:
    if not n:
        return "Unknown"
    if n < 1e6:
        return "{:.0f} KB".format(n / 1e3)
    return "{:.1f} MB".format(n / 1e6) if n < 1e8 else "{:.0f} MB".format(n / 1e6)


def jetpack_label(jp: Optional[str]) -> str:
    """jp6.2 -> '6.2', igx2.0 -> 'IGX 2.0'."""
    if not jp:
        return "Unknown"
    if jp.startswith("jp"):
        return jp[2:]
    m = re.match(r"([a-z]+)(.*)", jp)
    return "{} {}".format(m.group(1).upper(), m.group(2)) if m else jp
